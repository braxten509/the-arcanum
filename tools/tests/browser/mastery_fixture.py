def _install_legacy() -> None:
    stage = Path(tempfile.mkdtemp(prefix=f".{LEGACY_TOME_ID}-", dir=ROOT / "tomes"))
    try:
        _legacy_fixture(stage)
        stage.replace(LEGACY_TARGET)
        stage = Path()
    finally:
        if stage and stage.exists() and stage != Path("."):
            shutil.rmtree(stage)


def _install() -> None:
    _remove()
    stage = Path(tempfile.mkdtemp(prefix=f".{TOME_ID}-", dir=ROOT / "tomes"))
    try:
        contract, _sections = future_map(2)
        _manifest(stage)
        _section_files(stage, contract)
        write_working_assessments(stage)
        export_mastery_contract({"masteryEvidence": contract}, str(stage))
        generator = VariantGenerator(
            for_config({"name": "python"}), SemanticPass(), sandbox=PythonProofSandbox())
        for lab_path in write_labs(stage, contract):
            generator.generate(str(stage), str(lab_path))
        _state(stage, contract)
        (stage / MARKER).write_text("disposable browser fixture\n", encoding="utf-8")
        stage.replace(TARGET)
        stage = Path()
    finally:
        if stage and stage.exists() and stage != Path("."):
            shutil.rmtree(stage)
    try:
        _install_legacy()
    except Exception:
        _remove()
        raise


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=("install", "remove"))
    args = parser.parse_args()
    if args.action == "install":
        _install()
        print(TARGET)
    else:
        _remove()
        print(f"removed {TARGET}")


if __name__ == "__main__":
    main()
