def _remove() -> None:
    targets = [target for target in (TARGET, LEGACY_TARGET) if target.exists()]
    for target in targets:
        if not (target / MARKER).is_file():
            raise RuntimeError(f"refusing to remove unmarked directory: {target}")
    for target in targets:
        shutil.rmtree(target)


